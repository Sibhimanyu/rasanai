// Plan 12 D4: accessibility deliverables and checks that can be computed from numbers and records. Nothing here looks at pixels:
// callers pass colours, luminance series and scene records they already have (frame-gate, motion-gate, the score).
//
//   requiredDeliverables()    which text alternatives this film owes, from the brief's accessibility needs, its audience and its content
//   contrastRatio / checkContrast   WCAG relative-luminance contrast; thresholds are CONFIGURABLE (default 4.5 text, 3 large text / graphics)
//   distinctionsCheck()       important visual distinctions (series in a chart, states, warnings) must not rely on colour alone
//   reducedMotionPlan()       a deliberate reduced-motion FILM variant: which score motions are replaced and how. Distinct from Studio's
//                             "reduce animation" UI setting (a Swift/OS preference that never touches a rendered film)
//   flashRisk()               the general-flash screening hook over a caller-supplied per-frame relative-luminance series; `not_measured` without one
//   acceptance()              an accessibility report that NEVER says "accessible": it lists what was met, not met and not measured
// Pure; no I/O.
const arr = (x) => (Array.isArray(x) ? x : []);
const str = (x, d = "") => (typeof x === "string" ? x : d);
const num = (x, d = null) => (Number.isFinite(Number(x)) && x !== null && x !== "" ? Number(x) : d);

export const A11Y_DEFAULTS = Object.freeze({
  contrast_text: 4.5, contrast_large: 3, large_text_px_at_1080: 36,
  flash_per_second: 3, flash_luminance_delta: 0.1, flash_dark_ceiling: 0.8, flash_area_note: "the screening needs the area of the change; without it the result is conservative",
  source: "WCAG 2.x success criteria 1.4.3 and 2.3.1 as recorded by RasanAI; verify against the current edition",
  verified_at: null, needs_validation: true,
});
const cfg = (o = {}) => ({ ...A11Y_DEFAULTS, ...(o && typeof o === "object" ? Object.fromEntries(Object.entries(o).filter(([k]) => k in A11Y_DEFAULTS)) : {}) });

// ---- what the film owes ------------------------------------------------------------------------------------------------------------------------
// brief.accessibility: { captions, transcript, descriptive_transcript, audio_description, reduced_motion_film, deaf_or_hard_of_hearing, blind_or_low_vision, muted_safe }
// film: { has_speech, has_meaningful_sound, visual_meaning_beats (count of beats whose meaning is only visual), silent_visual_explanation }
export function requiredDeliverables({ brief = {}, profile = {}, film = {} } = {}) {
  const a = (brief && brief.accessibility) || {};
  const out = [], why = {};
  const need = (id, reason) => { if (!out.includes(id)) out.push(id); why[id] = reason; };
  if (a.captions !== false && (film.has_speech || film.has_meaningful_sound)) need("captions", film.has_speech ? "the film has speech" : "the film has meaningful non-speech sound");
  if (str(profile.captions && profile.captions.policy) === "burned_in_required") need("captions_burned_in", "the destination profile asks for burned-in captions");
  if (a.transcript || a.deaf_or_hard_of_hearing || film.has_speech) need("transcript", a.transcript ? "requested" : film.has_speech ? "speech exists: a text transcript is the baseline alternative" : "audience need");
  if (a.descriptive_transcript || a.blind_or_low_vision || (film.silent_visual_explanation && num(film.visual_meaning_beats, 0) > 0)) need("descriptive_transcript", film.silent_visual_explanation && !a.descriptive_transcript ? "a silent visual explanation still needs a textual description of what the viewer must understand" : "requested or audience need");
  if (a.audio_description) need("audio_description_track", "requested: a separate described-audio track (needs a voice and a mix; not generated by this plan's text files)");
  if (a.reduced_motion_film) need("reduced_motion_variant", "requested: a deliberate calmer film variant");
  if (profile.sound_assumption === "off" && a.muted_safe !== false) need("muted_safe_check", "sound is assumed off");
  return { deliverables: out, why };
}

// ---- contrast ----------------------------------------------------------------------------------------------------------------------------------
export function parseColour(c) {
  if (Array.isArray(c) && c.length >= 3) return c.slice(0, 3).map((v) => Math.max(0, Math.min(255, Number(v))));
  const s = str(c).trim().toLowerCase();
  let m = /^#([0-9a-f]{3})$/.exec(s); if (m) return [...m[1]].map((h) => parseInt(h + h, 16));
  m = /^#([0-9a-f]{6})(?:[0-9a-f]{2})?$/.exec(s); if (m) return [0, 2, 4].map((i) => parseInt(m[1].slice(i, i + 2), 16));
  m = /^rgba?\(\s*(\d+)[\s,]+(\d+)[\s,]+(\d+)/.exec(s); if (m) return [Number(m[1]), Number(m[2]), Number(m[3])];
  return null;
}
export function relativeLuminance(rgb) {
  const [r, g, b] = rgb.map((v) => { const x = v / 255; return x <= 0.03928 ? x / 12.92 : ((x + 0.055) / 1.055) ** 2.4; });
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}
export function contrastRatio(fg, bg) {
  const a = parseColour(fg), b = parseColour(bg);
  if (!a || !b) return null;
  const [hi, lo] = [relativeLuminance(a), relativeLuminance(b)].sort((x, y) => y - x);
  return Math.round(((hi + 0.05) / (lo + 0.05)) * 100) / 100;
}
// items: [{ id, fg, bg, size_px?, large?: bool, kind?: "text"|"graphic", over_media?: bool, frame_h? }]  bg may be unknown for text over footage: reported as not_measured
export function checkContrast(items, opts = {}) {
  const C = cfg(opts), results = [];
  for (const it of arr(items)) {
    const scale = num(it.frame_h, 1080) / 1080;
    const large = it.large === true || (num(it.size_px) !== null && it.size_px / scale >= C.large_text_px_at_1080);
    const need = it.kind === "graphic" || large ? C.contrast_large : C.contrast_text;
    const r = it.bg == null ? null : contrastRatio(it.fg, it.bg);
    if (r === null) results.push({ id: it.id, status: "not_measured", need, why: it.over_media ? "text over footage: sample the pixels behind it or add a scrim; no background colour was given" : "a colour could not be read" });
    else results.push({ id: it.id, status: r >= need ? "met" : "not_met", ratio: r, need });
  }
  return { results, not_met: results.filter((r) => r.status === "not_met").map((r) => r.id), not_measured: results.filter((r) => r.status === "not_measured").map((r) => r.id), thresholds_source: C.source, thresholds_need_validation: C.needs_validation };
}

// groups: [{ id, items: [{ id, channels: ["colour","shape","label","position","pattern","icon"] }] }]
export function distinctionsCheck(groups) {
  const problems = [];
  for (const g of arr(groups)) {
    const items = arr(g.items);
    if (items.length < 2) continue;
    const colourOnly = items.filter((i) => { const ch = arr(i.channels).map(String); return ch.includes("colour") && ch.length === 1; });
    if (colourOnly.length >= 2) problems.push({ group: g.id, items: colourOnly.map((i) => i.id), why: "these are told apart by colour alone: add a label, shape, pattern, icon or position difference" });
    else if (items.every((i) => !arr(i.channels).length)) problems.push({ group: g.id, why: "no distinguishing channel was recorded: cannot confirm it works without colour" });
  }
  return { ok: !problems.length, problems };
}

// ---- reduced-motion film variant ---------------------------------------------------------------------------------------------------------------
// score: motion/score.json shape (scenes[].motions or events); motions: [{ id, kind: "camera_move"|"parallax"|"scale"|"rotate"|"shake"|"flash"|"loop"|"transition"|"slide"|"fade"|"reveal", amount?: 0..1, seam?: bool }]
const REPLACE = {
  camera_move: { to: "locked_frame_or_slow_crossfade", keep: "the framing that holds the subject" },
  parallax: { to: "static_layers", keep: "the depth order" },
  scale: { to: "cut_or_fade_to_end_state", keep: "the end state" },
  rotate: { to: "cut_to_end_state", keep: "the end state" },
  shake: { to: "remove", keep: "the beat's timing marker (a cut or a still hold)" },
  flash: { to: "remove_or_soft_fade", keep: "the emphasis through a hold or a size change that does not move" },
  loop: { to: "single_state_or_one_pass", keep: "the meaning of the loop" },
  transition: { to: "crossfade_or_cut", keep: "the story seam" },
  slide: { to: "fade", keep: "the order of appearance" },
  reveal: { to: "fade_in_place", keep: "the order of appearance" },
  fade: { to: "keep", keep: "" },
};
export function reducedMotionPlan(motions, { threshold = 0.35 } = {}) {
  const changes = [], kept = [];
  for (const m of arr(motions)) {
    const r = REPLACE[m.kind] || { to: "review", keep: "" };
    const amount = num(m.amount, 1);
    if (r.to === "keep" || (amount < threshold && !["flash", "shake", "loop"].includes(m.kind))) { kept.push({ id: m.id, kind: m.kind, why: r.to === "keep" ? "gentle by nature" : `small (${amount}) and not flashing` }); continue; }
    changes.push({ id: m.id, kind: m.kind, replace_with: r.to, preserve: r.keep, timing: "same start and duration unless the owner changes it (the score stays the one timing authority)" });
  }
  return {
    variant: "reduced_motion_film", threshold_is_a_default: true, changes, kept, unknown_kinds: changes.filter((c) => c.replace_with === "review").map((c) => c.id),
    distinct_from: "Studio's reduce-animation setting, which is a UI preference and never changes a rendered film",
    needs: ["a render of the variant (not done here)", "a flash screening of the result"], story_changed: false,
  };
}

// ---- flashing ------------------------------------------------------------------------------------------------------------------------------------
// series: [{ t, luminance }] relative luminance 0..1 per frame (or per sampled frame). Returns the worst one-second window of opposing luminance changes.
export function flashRisk(series, opts = {}) {
  const C = cfg(opts);
  const s = arr(series).map((x) => ({ t: num(x.t), l: num(x.luminance) })).filter((x) => x.t !== null && x.l !== null).sort((a, b) => a.t - b.t);
  if (s.length < 3) return { status: "not_measured", why: "no luminance series was supplied: the hook is ready, nothing was measured", thresholds_source: C.source };
  // an opposing change = a swing of the luminance direction whose size passes the delta and whose darker side is under the ceiling
  const swings = [];
  let dir = 0, extremum = s[0];
  for (let i = 1; i < s.length; i++) {
    const d = s[i].l - s[i - 1].l;
    const nd = d > 0 ? 1 : d < 0 ? -1 : 0;
    if (nd !== 0 && dir !== 0 && nd !== dir) {
      const delta = Math.abs(s[i - 1].l - extremum.l);
      if (delta >= C.flash_luminance_delta && Math.min(s[i - 1].l, extremum.l) < C.flash_dark_ceiling) swings.push({ t: s[i - 1].t, delta });
      extremum = s[i - 1];
    }
    if (nd !== 0) dir = nd;
  }
  let worst = 0, at = null;
  for (let i = 0; i < swings.length; i++) { const n = swings.filter((w) => w.t >= swings[i].t && w.t < swings[i].t + 1).length; if (n > worst) { worst = n; at = swings[i].t; } }
  const flashes = Math.floor(worst / 2); // a flash is a pair of opposing changes
  const limit = C.flash_per_second;
  return { status: flashes > limit ? "risk" : "no_risk_found_in_this_series", flashes_in_worst_second: flashes, at_s: at, limit, note: C.flash_area_note, samples: s.length, warning: flashes > limit ? "more than the recorded flashes per second: soften, slow or remove the change before delivery" : "screened only over the supplied samples; this is not a certification", thresholds_source: C.source, thresholds_need_validation: C.needs_validation };
}

// ---- the honest report --------------------------------------------------------------------------------------------------------------------------
// checks: { name: { status: "met"|"not_met"|"not_measured"|"not_applicable", note? } }
export function acceptance(checks) {
  const met = [], not_met = [], not_measured = [];
  for (const [k, v] of Object.entries(checks || {})) { const st = v && v.status; if (st === "met") met.push(k); else if (st === "not_met") not_met.push({ check: k, note: v.note || "" }); else if (st === "not_applicable") continue; else not_measured.push({ check: k, note: v && v.note || "not run" }); }
  return { met, not_met, not_measured, accessible_claim: null, note: "subtitles, a script that claims compliance, or a passing contrast check do not make a film accessible; this report lists only what was checked", needs_human_review: true };
}
